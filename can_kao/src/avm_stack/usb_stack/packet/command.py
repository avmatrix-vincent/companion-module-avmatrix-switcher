    PRE_UPG_MCU_APP = 0x02
    READY_UPG_MCU_APP = 0x10
    MCU_APP_UPG_DATA = 0x11
    COMPLETE_UPG_MCU_APP = 0x13
    POST_UPG_MCU_APP = 0x14
    GET_MCU_VER = 0x15
    QUERY_DEV_INFO = 0x16
    QUERY_CONFIG_CHIPS = 0x17
    ACTIVE_MCU_BEFORE_UPG_FPGA = 0x42
    PRE_UPG_FPGA = 0x45
    READY_UPG_FPGA = 0x40
    FPGA_UPG_DATA = 0x41
    COMPLETE_UPG_FPGA = 0x43
    GET_FPGA_VER = 0x46
    READ_REGISTER = 0xA0
    WRITE_REGISTER = 0xA1
